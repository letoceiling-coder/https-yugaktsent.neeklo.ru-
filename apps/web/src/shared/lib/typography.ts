/**
 * Микротипографика для текстов сайта.
 *
 * Два правила, которые заметны глазом на узких колонках и на телефоне:
 * короткий предлог не должен оставаться в конце строки, а число не должно
 * отрываться от единицы измерения. Оба решаются неразрывным пробелом.
 */

const NBSP = ' ';

/** Предлоги, союзы и частицы, после которых перенос строки выглядит ошибкой. */
const SHORT_WORDS = [
  'а', 'в', 'и', 'к', 'о', 'с', 'у', 'я',
  'до', 'за', 'из', 'их', 'ко', 'на', 'не', 'но', 'об', 'от', 'по', 'со', 'то', 'во',
  'без', 'для', 'или', 'как', 'над', 'обо', 'при', 'про', 'три', 'что', 'это',
  'под', 'уже', 'при', 'что',
];

/** Единицы измерения, которые нельзя отрывать от числа. */
const UNITS = [
  'м²', 'м2', 'га', 'сот', 'сот.', 'кв', 'кв.', 'руб', 'руб.', '₽', '%',
  'млн', 'млрд', 'тыс', 'тыс.', 'мин', 'ч', 'мес', 'мес.', 'года', 'год', 'лет',
  'этаж', 'этажа', 'этажей', 'комн', 'комн.',
];

const shortWordRe = new RegExp(`(^|[\\s(«"'])(${SHORT_WORDS.join('|')}) `, 'gi');
const unitRe = new RegExp(`(\\d) (${UNITS.map((u) => u.replace('.', '\\.')).join('|')})(?![\\p{L}])`, 'giu');

/**
 * Расставляет неразрывные пробелы: после коротких слов и между числом и единицей.
 * Возвращает строку, пригодную для прямой вставки в JSX.
 */
export function typo(text: string): string {
  let out = text;
  // Два прохода: «и в доме» — первый проход съедает пробел после «и»,
  // второй добирает «в», потому что регулярка смотрит на предыдущий разделитель.
  for (let i = 0; i < 2; i++) {
    out = out.replace(shortWordRe, (_m, lead: string, word: string) => `${lead}${word}${NBSP}`);
  }
  out = out.replace(unitRe, (_m, digit: string, unit: string) => `${digit}${NBSP}${unit}`);
  return out;
}

/** Короткий алиас для вставки в разметку. */
export const t = typo;
